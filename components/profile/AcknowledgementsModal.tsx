import React, { useCallback, useMemo, useState } from 'react';
import {
  FlatList,
  Linking,
  Modal,
  Platform,
  Pressable,
  StyleSheet,
  Text,
  TextInput,
  View,
  type ListRenderItem,
} from 'react-native';
import Ionicons from '@expo/vector-icons/Ionicons';

import { Screen } from '@/components/common/Screen';
import { fontFamilies } from '@/theme/typography';
import { ACKNOWLEDGEMENTS } from '@/constants/legal/acknowledgements';
import { LegalHeaderBar, LegalSectionView, RichText, legalStyles } from './LegalDocumentModal';
import licensesJson from '@/assets/licenses.json';

// Profile → Acknowledgements. Same look as the Disclaimer (shared header,
// section and text pieces). Section 1 is followed by the open-source list
// from assets/licenses.json (generated by `npm run licenses`, bundled, so it
// works offline): a search box, the package count, and one row per package
// that expands to show its licence. A single FlatList holds everything so
// the ~700 rows stay virtualized; only the expanded row renders its text.

export interface LicenseEntry {
  name: string;
  version: string;
  license: string;
  repository: string | null;
  text: string;
}

const LICENSES = licensesJson as LicenseEntry[];
const [OPEN_SOURCE, ...OTHER_SECTIONS] = ACKNOWLEDGEMENTS.sections;
const MONO = Platform.select({ ios: 'Menlo', android: 'monospace', default: 'monospace' });

const LicenseRow = React.memo(function LicenseRow({
  item,
  expanded,
  onToggle,
}: {
  item: LicenseEntry;
  expanded: boolean;
  onToggle: (name: string) => void;
}) {
  return (
    <View style={styles.row}>
      <Pressable
        onPress={() => onToggle(item.name)}
        style={({ pressed }) => [styles.rowHead, pressed && styles.rowPressed]}
        accessibilityRole="button"
        accessibilityLabel={`${item.name}, version ${item.version}, ${item.license} licence`}
        accessibilityHint={expanded ? 'Hides the licence text' : 'Shows the licence text'}
        accessibilityState={{ expanded }}
      >
        <View style={styles.rowTitleCol}>
          <Text style={styles.pkgName}>{item.name}</Text>
          <Text style={styles.pkgVersion}>v{item.version}</Text>
        </View>
        <View style={styles.chip}>
          <Text style={styles.chipText} numberOfLines={1}>
            {item.license}
          </Text>
        </View>
        <Ionicons name={expanded ? 'chevron-up' : 'chevron-down'} size={16} color="#71717A" />
      </Pressable>

      {expanded && (
        <View style={styles.rowBody}>
          <Text style={styles.licenseText} selectable>
            {item.text}
          </Text>
          {!!item.repository && (
            <Text
              style={styles.repo}
              onPress={() => Linking.openURL(item.repository!).catch(() => {})}
              accessibilityRole="link"
              accessibilityLabel={`Source code for ${item.name}`}
            >
              {item.repository}
            </Text>
          )}
        </View>
      )}
    </View>
  );
});

export interface AcknowledgementsModalProps {
  visible: boolean;
  onClose: () => void;
}

export function AcknowledgementsModal({ visible, onClose }: AcknowledgementsModalProps) {
  const [query, setQuery] = useState('');
  const [expanded, setExpanded] = useState<string | null>(null);

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    return q ? LICENSES.filter((p) => p.name.toLowerCase().includes(q)) : LICENSES;
  }, [query]);

  const toggle = useCallback((name: string) => setExpanded((cur) => (cur === name ? null : name)), []);

  const renderItem: ListRenderItem<LicenseEntry> = useCallback(
    ({ item }) => <LicenseRow item={item} expanded={expanded === item.name} onToggle={toggle} />,
    [expanded, toggle]
  );

  const close = () => {
    setQuery('');
    setExpanded(null);
    onClose();
  };

  const countText = query.trim()
    ? `${filtered.length} of ${LICENSES.length} packages`
    : `${LICENSES.length} packages`;

  const header = (
    <View>
      <Text style={legalStyles.updated}>Last updated: {ACKNOWLEDGEMENTS.lastUpdated}</Text>
      {!!ACKNOWLEDGEMENTS.intro && <RichText text={ACKNOWLEDGEMENTS.intro} style={legalStyles.intro} />}
      <LegalSectionView number={1} section={OPEN_SOURCE} />

      <View style={styles.searchBox}>
        <Ionicons name="search" size={16} color="#71717A" />
        <TextInput
          style={styles.searchInput}
          value={query}
          onChangeText={setQuery}
          placeholder="Search packages"
          placeholderTextColor="#52525B"
          autoCapitalize="none"
          autoCorrect={false}
          clearButtonMode="while-editing"
          accessibilityLabel="Search open-source packages by name"
        />
      </View>
      <Text style={styles.count} accessibilityLiveRegion="polite">
        {countText}
      </Text>
    </View>
  );

  const footer = (
    <View>
      {OTHER_SECTIONS.map((section, i) => (
        <LegalSectionView key={section.heading} number={i + 2} section={section} />
      ))}
      <View style={{ height: 32 }} />
    </View>
  );

  return (
    <Modal visible={visible} animationType="slide" presentationStyle="fullScreen" statusBarTranslucent onRequestClose={close}>
      <Screen style={legalStyles.screen}>
        <LegalHeaderBar title={ACKNOWLEDGEMENTS.title} onBack={close} />
        <FlatList
          data={filtered}
          keyExtractor={(item) => item.name}
          renderItem={renderItem}
          extraData={expanded}
          ListHeaderComponent={header}
          ListFooterComponent={footer}
          ListEmptyComponent={<Text style={styles.empty}>No packages match “{query.trim()}”.</Text>}
          contentContainerStyle={legalStyles.scrollContent}
          showsVerticalScrollIndicator={false}
          keyboardShouldPersistTaps="handled"
          keyboardDismissMode="on-drag"
          initialNumToRender={20}
          maxToRenderPerBatch={20}
          windowSize={11}
          removeClippedSubviews={Platform.OS === 'android'}
        />
      </Screen>
    </Modal>
  );
}

